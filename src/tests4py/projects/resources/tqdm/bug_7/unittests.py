import unittest


class TestsFailing(unittest.TestCase):
    def test_diversity_1(self):
        import io, sys
        from tqdm import main
        sys.argv = ['', '--desc', 'omxlzpg-tlrjiwxc']
        sys.stdin = io.StringIO('pzwyshxl' + '\n')
        cap = io.StringIO()
        real = sys.stdout
        sys.stdout = cap
        try:
            main(fp=io.StringIO())
        finally:
            sys.stdout = real
        self.assertEqual('pzwyshxl', cap.getvalue().rstrip('\n'))

